// Run against scripts/integration.py --serve (synthetic data only).
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,
    ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {})});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:960}});
    page.setDefaultTimeout(7000);
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const base=process.env.SCENE_URL || 'http://127.0.0.1:50109';
    await page.goto(base+'/outdoor',{waitUntil:'domcontentloaded'});
    await page.waitForSelector('#od-roads path',{state:'attached'});
    const before=await (await page.request.get(base+'/api/outdoor/state')).json();
    assert.equal(before.is_active,true);
    assert.equal(before.map.example_data,true,'Browser test requires the synthetic example');
    const view=await page.locator('#od-svg').getAttribute('viewBox');
    for (const mode of ['capture','merge','plan','view']) {
      await page.locator(`[data-mode="${mode}"]`).click();
      assert.equal(await page.locator('#od-svg').getAttribute('viewBox'),view);
      assert(await page.locator('#od-panel h2').textContent());
    }
    await page.locator('#od-gait').uncheck();
    assert.equal(await page.locator('#od-roads path[style*="#ff6666"]').count(),0);
    await page.locator('#od-gait').check();
    await page.locator('#od-quality-toggle').uncheck();
    assert.equal(await page.locator('#od-quality path').count(),0);
    await page.locator('#od-quality-toggle').check();
    const map=before.map, roads=map.network.roads;
    const points=roads.flatMap(r=>r.points);
    const start=points.reduce((a,b)=>a.x<b.x?a:b), goal=points.reduce((a,b)=>a.y>b.y?a:b);
    const response=await page.request.post(base+'/api/outdoor/plan_route',{data:{map_id:map.map_id,version:map.version,start,goal}});
    const route=await response.json();
    assert.equal(route.ok,true,JSON.stringify(route));
    assert(route.length_m>4,JSON.stringify(route));
    const reverse=await (await page.request.post(base+'/api/outdoor/plan_route',{data:{map_id:map.map_id,version:map.version,start:goal,goal:start}})).json();
    assert(Math.abs(reverse.length_m-route.length_m)<1e-6);
    const clickPoint = async point => {
      const screen = await page.locator('#od-svg').evaluate((svg, p) => {
        const point = svg.createSVGPoint();
        point.x=p.x; point.y=-p.y;
        const screen=point.matrixTransform(svg.getScreenCTM());
        return {x:screen.x,y:screen.y};
      }, point);
      await page.mouse.click(screen.x,screen.y);
    };
    const placeName='SYNTHETIC 快递柜 '+Date.now(),editedName=placeName+' edited';
    await page.locator('[data-command="mark-poi"]').click();
    await clickPoint(goal);
    await page.locator('#od-poi-name').fill(placeName);
    await page.waitForTimeout(1200);
    assert.equal(await page.locator('#od-poi-name').inputValue(),placeName);
    await page.locator('#od-poi-editor button[type="submit"]').click();
    const place = page.locator('#od-places [data-place]').filter({hasText:placeName});
    await place.waitFor();
    await page.reload();
    await place.waitFor();
    await place.locator('circle').click();
    assert(await page.locator('[data-mode="view"]').evaluate(el=>el.classList.contains('active')));
    const annotated = await (await page.request.get(base+'/api/outdoor/state')).json();
    const annotation = annotated.annotations.find(a=>a.name===placeName);
    assert((await page.locator('#od-panel').textContent()).includes(annotation.points[0][0].toFixed(2)));
    const first=roads[0].points, a=first[0], b=first[1];
    const editedGoal={x:(a.x+b.x)/2,y:(a.y+b.y)/2};
    await page.locator('[data-command="edit-place"]').click();
    await page.locator('#od-poi-name').fill(editedName);
    await clickPoint(editedGoal);
    const editedResponse=page.waitForResponse(r=>r.request().method()==='PUT'&&r.url().includes('/api/regions/'));
    await page.locator('#od-poi-editor button[type="submit"]').click();
    const editResult=await (await editedResponse).json();
    assert.equal(editResult.ok,true,JSON.stringify(editResult));
    assert(Math.hypot(editResult.annotation.points[0][0]-editedGoal.x,editResult.annotation.points[0][1]-editedGoal.y)<.1,JSON.stringify({editedGoal,editResult}));
    const editedPlace=page.locator('#od-places [data-place]').filter({hasText:editedName});
    await editedPlace.waitFor();
    await page.reload();
    await editedPlace.waitFor();
    await editedPlace.locator('circle').click();
    assert(await page.locator('[data-mode="view"]').evaluate(el=>el.classList.contains('active')));
    const editedState = await (await page.request.get(base+'/api/outdoor/state')).json();
    const edited=editedState.annotations.find(a=>a.annotation_id===annotation.annotation_id);
    assert.equal(edited.name,editedName);
    assert(Math.hypot(edited.points[0][0]-editedGoal.x,edited.points[0][1]-editedGoal.y)<.1);
    await page.locator('[data-command="edit-place"]').click();
    await page.locator('#od-poi-name').fill('UNSAVED');
    await page.locator('[data-command="plan-place"]').click();
    assert.equal(await page.locator('#od-poi-editor').isVisible(),false);
    assert(await page.locator('[data-mode="plan"]').evaluate(el=>el.classList.contains('active')));
    assert.equal(await page.locator('#od-place option:checked').textContent(),editedName);
    await page.locator('[data-mode="view"]').click();
    assert.equal(await page.locator('#od-markers circle[fill="#c2ead8"]').count(),0);
    assert.equal(await editedPlace.count(),1);
    await page.locator('[data-mode="plan"]').click();
    assert.equal(await page.locator('#od-place option:checked').textContent(),editedName);
    assert.equal(await page.locator('#od-markers circle[fill="#c2ead8"]').count(),1);
    await page.locator('[data-command="select-start"]').click();
    await editedPlace.locator('circle').click();
    assert.equal(await page.locator('#od-panel .od-fields span').nth(1).textContent(),await page.evaluate(()=>t('outdoor.manual')));
    assert.equal(await page.locator('#od-place option:checked').textContent(),editedName);
    await page.locator('[data-command="select-start"]').click();
    await clickPoint(start);
    const planned = page.waitForResponse(r=>r.url().endsWith('/api/outdoor/plan_route')&&r.request().method()==='POST');
    await page.locator('[data-command="plan"]').click();
    const plannedResponse=await planned;
    assert.deepEqual(plannedResponse.request().postDataJSON().goal,{x:edited.points[0][0],y:edited.points[0][1]});
    const namedRoute = await plannedResponse.json();
    assert.equal(namedRoute.ok,true,JSON.stringify(namedRoute));
    assert(Math.hypot(namedRoute.goal.x-editedGoal.x,namedRoute.goal.y-editedGoal.y)<.1);
    await page.locator('#od-route path').waitFor({state:'attached'});
    await page.locator('[data-mode="view"]').click();
    assert.equal(await page.locator('#od-route').locator('*').count(),0);
    assert.equal(await page.locator('#od-markers circle[fill="#c2ead8"], #od-markers circle[fill="#84a9ee"]').count(),0);
    await editedPlace.locator('circle').click();
    await page.locator('[data-command="edit-place"]').click();
    await page.locator('#od-poi-name').fill('UNSAVED');
    page.once('dialog',dialog=>dialog.dismiss());
    await page.locator('[data-command="delete-place"]').click();
    assert.equal(await editedPlace.count(),1);
    assert.equal(await page.locator('#od-poi-name').inputValue(),'UNSAVED');
    page.once('dialog',dialog=>dialog.accept());
    const deleted=page.waitForResponse(r=>r.request().method()==='DELETE'&&r.url().includes('/api/regions/'));
    await page.locator('[data-command="delete-place"]').click();
    assert.equal((await deleted).ok(),true);
    await page.locator('#od-poi-editor').waitFor({state:'hidden'});
    await page.reload();
    await page.waitForSelector('#od-panel h2');
    assert.equal(await editedPlace.count(),0);
    await page.screenshot({path:process.env.SCENE_SCREENSHOT || '/tmp/outdoor-scene.png',fullPage:true});
    await page.locator('.scene-types a').first().click();
    const after=await (await page.request.get(base+'/api/outdoor/state')).json();
    assert.equal(after.binding.map_id,before.binding.map_id);
    assert.equal(after.binding.version,before.binding.version);
    if (process.env.SCENE_FIXTURE_CONTROL) {
      const fs = require('node:fs');
      await page.goto(base+'/outdoor');
      await page.waitForSelector('#od-roads path',{state:'attached'});
      await page.locator('[data-mode="capture"]').click();
      await page.locator('[data-command="append"]').click();
      await page.waitForSelector('[data-command="pause"]');
      assert(await page.locator('[data-mode="view"]').isDisabled());
      const blocked=await page.request.post(base+'/api/maps/load',{data:{map_id:map.map_id,map_type:'outdoor'}});
      assert.equal(blocked.status(),409);
      await page.locator('[data-command="pause"]').click();
      await page.waitForSelector('[data-command="resume"]');
      await page.locator('[data-command="resume"]').click();
      await page.waitForSelector('[data-command="pause"]');
      const control=process.env.SCENE_FIXTURE_CONTROL;
      fs.writeFileSync(control+'.browser.tmp',JSON.stringify({x:2,y:5}));
      fs.renameSync(control+'.browser.tmp',control);
      await page.waitForTimeout(2100);
      await page.locator('[data-command="stop"]').click();
      await page.waitForSelector('[data-command="preview-merge"]');
      await page.locator('[data-command="preview-merge"]').click();
      await page.waitForSelector('[data-command="apply"]');
      assert(await page.locator('[data-command="apply"]').isDisabled());
      await page.locator('[data-mode="capture"]').click();
      page.once('dialog',dialog=>dialog.accept());
      await page.locator('[data-command="discard"]').click();
      await page.waitForSelector('[data-command="append"]');
    }
    await page.goto(base+'/regions?map_type=outdoor');
    await page.waitForSelector('iframe');
    assert((await page.locator('iframe').getAttribute('src')).includes('map_type=outdoor'));
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,checks:['four modes preserve view','gait and quality layers','branch forward/reverse planning','place view, rename, reposition, delete, reload and explicit route preview','tabs do not load maps','outdoor annotation editor',...(process.env.SCENE_FIXTURE_CONTROL?['capture pause/resume and map-load guard','unreviewed merge cannot submit']:[])],length_m:route.length_m}));
  } finally {
    await browser.close();
  }
})().catch(error=>{console.error(error);process.exit(1)});
